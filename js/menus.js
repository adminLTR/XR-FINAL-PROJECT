export function findDish(menuId, dishId) {
  const menu = MENUS[menuId];
  if (!menu || !dishId) return null;
  for (const section of menu.sections) {
    const dish = section.dishes.find((item) => item.id === dishId);
    if (dish) return { dish, section };
  }
  return null;
}

export function dishCount(menuId) {
  const menu = MENUS[menuId];
  if (!menu) return 0;
  return menu.sections.reduce((total, section) => total + section.dishes.length, 0);
}
